-- 9. attendance (The Operational Clocking System)
-- Tracks check-in/check-out for a volunteer at a specific event.
-- calculated_hours is auto-computed from check_in and check_out.
CREATE TABLE public.attendance (
    id               UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    volunteer_id     UUID REFERENCES public.volunteer_profiles(id) ON DELETE CASCADE NOT NULL,
    event_id         UUID REFERENCES public.events(id) ON DELETE CASCADE NOT NULL,
    check_in         TIMESTAMP WITH TIME ZONE NOT NULL,
    check_out        TIMESTAMP WITH TIME ZONE,
    calculated_hours NUMERIC(5, 2) GENERATED ALWAYS AS (
        EXTRACT(EPOCH FROM (check_out - check_in)) / 3600
    ) STORED,
    CONSTRAINT unique_volunteer_event_attendance UNIQUE (volunteer_id, event_id)
);
COMMENT ON TABLE public.attendance IS 'Tracks volunteer check-in/check-out per event. Hours are auto-calculated.';

