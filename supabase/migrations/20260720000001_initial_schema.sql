-- 4a. Auto-create profile on new user signup
-- Fires immediately when a new row is inserted into auth.users.
-- Reads metadata set during signup to populate full_name and role.
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
    INSERT INTO public.profiles (id, full_name, role)
    VALUES (
        NEW.id,
        COALESCE(NEW.raw_user_meta_data->>'full_name', 'New User'),
        COALESCE((NEW.raw_user_meta_data->>'role')::public.user_role, 'volunteer')
    );
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();


-- 4b. Recalculate volunteer total hours after each check-out
-- Fires after INSERT or UPDATE of check_out on the attendance table.
-- Sums ALL calculated_hours for the volunteer to prevent drift.
CREATE OR REPLACE FUNCTION public.update_volunteer_total_hours()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.check_out IS NOT NULL THEN
        UPDATE public.volunteer_profiles
        SET total_hours = (
            SELECT COALESCE(SUM(calculated_hours), 0)
            FROM public.attendance
            WHERE volunteer_id = NEW.volunteer_id
              AND check_out IS NOT NULL
        )
        WHERE id = NEW.volunteer_id;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_update_volunteer_hours
    AFTER INSERT OR UPDATE OF check_out ON public.attendance
    FOR EACH ROW EXECUTE FUNCTION public.update_volunteer_total_hours();


-- 4c. Helper function: get the role of the currently authenticated user
